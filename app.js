function calc() {
  const car = carById($("#calc-car").value);
  const km = Number($("#calc-km").value) || 0;
  const trips = Number($("#calc-trips").value) || 0;
  const city = Number($("#calc-city").value) || 0;
  const idle = Number($("#calc-idle").value) || 0;
  const l100 = Number($("#calc-l100").value) || car.consumption;
  const pBy = Number($("#calc-by").value) || 0;
  const pPl = Number($("#calc-pl").value) || 0;
  const dist = km * 2 * trips + city;
  const liters = dist / 100 * l100 + idle * 1.0;
  const polish = Math.max(0, liters - car.tank);
  const home = Math.min(liters, car.tank);
  const cost = home * pBy + polish * pPl;
  const allPolish = liters * pPl;
  const days = liters > 0 ? car.tank / liters : 0;
  const fit = polish === 0
    ? "Бак закрывает этот день заправкой в Гродно."
    : `Не хватает ${polish.toFixed(0)} л. Их придётся купить в Польше.`;
  $("#calc-out").innerHTML = `
    <div class="stat"><b>${liters.toFixed(0)} л</b><span>уйдёт за такой день</span></div>
    <div class="stat"><b>${car.tank} л</b><span>бак ${esc(car.name)}</span></div>
    <div class="stat"><b>${cost.toFixed(0)} Br</b><span>топливо, если бак залит дома</span></div>
    <div class="stat"><b>${(allPolish - cost).toFixed(0)} Br</b><span>дешевле, чем залиться целиком в Польше</span></div>
    <p style="grid-column:1/-1;margin:0">${esc(fit)} Одного бака хватает примерно на ${days.toFixed(1)} таких дня. Простой принят как 1 литр в час.</p>`;
}

function fillCalcCars() {
  const select = $("#calc-car");
  select.innerHTML = CARS.filter((c) => c.id !== "skip").map((c) =>
    `<option value="${c.id}">${esc(c.name)} · ${c.tank} л</option>`
  ).join("");
  select.value = "caravelle";
  select.addEventListener("change", () => {
    $("#calc-l100").value = carById(select.value).consumption;
    calc();
  });
}

